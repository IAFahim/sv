using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Sv.Generators;

[Generator]
public sealed class SvSchemaGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var schemas = context.SyntaxProvider.ForAttributeWithMetadataName(
            "Sv.SvSchemaAttribute",
            static (node, _) => node is ClassDeclarationSyntax,
            static (ctx, ct) => SchemaModelFactory.Create((ClassDeclarationSyntax)ctx.TargetNode, (INamedTypeSymbol)ctx.TargetSymbol, ct));

        context.RegisterSourceOutput(schemas, static (production, model) =>
        {
            foreach (var error in model.Errors.Items)
            {
                production.ReportDiagnostic(Diagnostic.Create(
                    new DiagnosticDescriptor(error.Id, error.Title, error.Message, "SvSchema", DiagnosticSeverity.Error, true),
                    error.Location?.ToLocation()));
            }

            if (model.Emit)
            {
                production.AddSource(HintName(model), SourceText.From(Render(model), Encoding.UTF8));
            }
        });
    }

    static string HintName(SchemaModel model)
    {
        return model.Namespace.Length == 0
            ? $"SvSchema.{model.Name}.g.cs"
            : $"SvSchema.{model.Namespace}.{model.Name}.g.cs";
    }

    static string Render(SchemaModel model)
    {
        var text = new StringBuilder(2048);
        text.AppendLine("// <auto-generated by Sv.Generators />");
        var nested = model.Namespace.Length > 0;
        if (nested)
        {
            text.Append("namespace ").Append(model.Namespace).AppendLine();
            text.AppendLine("{");
        }

        AppendSchemaClass(text, model, nested ? 1 : 0);

        if (nested)
        {
            text.AppendLine("}");
        }

        return text.ToString();
    }

    static void AppendSchemaClass(StringBuilder text, SchemaModel model, int depth)
    {
        var pad = new string(' ', depth * 4);
        text.Append(pad).Append(model.Accessibility).Append(" static partial class ").Append(model.Name).AppendLine();
        text.Append(pad).Append('{').AppendLine();
        text.Append(pad).Append("    public static global::Sv.Schema Schema { get; }").AppendLine();
        foreach (var entry in model.Entries.Items)
        {
            text.AppendLine();
            var type = entry.Kind == SchemaModelFactory.IntrinsicKind ? "global::Sv.IntrinsicId" : "global::Sv.StatId";
            text.Append(pad).Append("    public static ").Append(type).Append(' ').Append(entry.Name).Append(" { get; }").AppendLine();
        }

        text.AppendLine();
        text.Append(pad).Append("    static ").Append(model.Name).Append("()").AppendLine();
        text.Append(pad).Append("    {").AppendLine();
        text.Append(pad).Append("        var builder = global::Sv.SchemaBuilder.Create();").AppendLine();
        foreach (var entry in model.Entries.Items)
        {
            if (entry.Kind == SchemaModelFactory.StatKind)
            {
                text.Append(pad).Append("        builder.Stat(").Append(Literal(entry.Name)).Append(", ").Append(Literal(entry.Base)).Append(");").AppendLine();
            }
            else if (entry.Kind == SchemaModelFactory.DerivedKind)
            {
                text.Append(pad).Append("        builder.Derived(").Append(Literal(entry.Name)).Append(", ").Append(Literal(entry.Base)).Append(", new (string, float)[] { ");
                for (var i = 0; i < entry.Sources.Items.Length; i++)
                {
                    if (i > 0)
                    {
                        text.Append(", ");
                    }

                    text.Append('(').Append(Literal(entry.Sources.Items[i].Name)).Append(", ").Append(Literal(entry.Sources.Items[i].Coefficient)).Append(')');
                }

                text.Append(" });").AppendLine();
            }
            else
            {
                text.Append(pad).Append("        builder.Intrinsic(").Append(Literal(entry.Name)).Append(");").AppendLine();
            }
        }

        text.Append(pad).Append("        Schema = builder.Build();").AppendLine();
        foreach (var entry in model.Entries.Items)
        {
            if (entry.Kind == SchemaModelFactory.IntrinsicKind)
            {
                text.Append(pad).Append("        ").Append(entry.Name).Append(" = Schema.Intrinsic(").Append(Literal(entry.Name)).Append(");").AppendLine();
            }
            else
            {
                text.Append(pad).Append("        ").Append(entry.Name).Append(" = Schema.Stat(").Append(Literal(entry.Name)).Append(");").AppendLine();
            }
        }

        text.Append(pad).Append("    }").AppendLine();
        foreach (var entry in model.Entries.Items)
        {
            if (entry.Kind == SchemaModelFactory.IntrinsicKind)
            {
                continue;
            }

            text.AppendLine();
            text.Append(pad).Append("    public static float Get").Append(entry.Name).Append("(global::Sv.Board board, int slot) => board.Output(").Append(entry.Name).Append(")[slot];").AppendLine();
        }

        text.Append(pad).Append('}').AppendLine();
    }

    static string Literal(string value)
    {
        var text = new StringBuilder(value.Length + 2);
        text.Append('"');
        foreach (var c in value)
        {
            if (c == '\\' || c == '"')
            {
                text.Append('\\').Append(c);
            }
            else if (c < ' ')
            {
                text.Append("\\u").Append(((int)c).ToString("X4", CultureInfo.InvariantCulture));
            }
            else
            {
                text.Append(c);
            }
        }

        text.Append('"');
        return text.ToString();
    }

    static string Literal(float value)
    {
        return value.ToString("R", CultureInfo.InvariantCulture) + "f";
    }
}

public static class SchemaModelFactory
{
    public const byte StatKind = 0;
    public const byte DerivedKind = 1;
    public const byte IntrinsicKind = 2;

    const string ForwardSource = "SVSGEN01";
    const string UnknownSource = "SVSGEN02";
    const string DuplicateName = "SVSGEN03";
    const string NotPartialClass = "SVSGEN04";
    const string InvalidName = "SVSGEN05";
    const string LengthMismatch = "SVSGEN06";
    const string NonFinite = "SVSGEN07";
    const string EmptySchema = "SVSGEN08";
    const string ReservedName = "SVSGEN09";

    static readonly EquatableArray<StatEntry> EmptyEntries = new(ImmutableArray<StatEntry>.Empty);

    static readonly string[] Reserved =
    {
        "Schema", "Equals", "GetHashCode", "ToString", "ReferenceEquals", "GetType", "MemberwiseClone", "Finalize"
    };

    sealed record RawEntry(byte Kind, string Name, float Base, (string Name, float Coefficient)[] Sources, bool LengthMismatch, LocationInfo? Location);

    public static SchemaModel Create(ClassDeclarationSyntax node, INamedTypeSymbol symbol, CancellationToken ct)
    {
        var errors = new List<ErrorInfo>();
        if (!node.Modifiers.Any(SyntaxKind.PartialKeyword)
            || !node.Modifiers.Any(SyntaxKind.StaticKeyword)
            || symbol.ContainingType is not null
            || symbol.Arity != 0)
        {
            errors.Add(new ErrorInfo(
                NotPartialClass,
                "Sv schema",
                $"sv: schema class '{symbol.Name}' must be a top-level static partial class",
                LocationInfo.From(node.GetLocation())));
            return new SchemaModel(NamespaceOf(symbol), symbol.Name, AccessibilityOf(symbol), EmptyEntries, ToErrors(errors), false);
        }

        var raw = CollectRaw(symbol, ct);
        var allStatNames = new HashSet<string>(StringComparer.Ordinal);
        var allIntrinsicNames = new HashSet<string>(StringComparer.Ordinal);
        foreach (var entry in raw)
        {
            if (entry.Kind == IntrinsicKind)
            {
                allIntrinsicNames.Add(entry.Name);
            }
            else
            {
                allStatNames.Add(entry.Name);
            }
        }

        var seenStats = new HashSet<string>(StringComparer.Ordinal);
        var seenIntrinsics = new HashSet<string>(StringComparer.Ordinal);
        var entries = new List<StatEntry>();
        foreach (var entry in raw)
        {
            ct.ThrowIfCancellationRequested();
            var valid = true;
            if (!IsValidIdentifier(entry.Name))
            {
                errors.Add(new ErrorInfo(InvalidName, "Sv schema", $"sv: name '{entry.Name}' must be a valid C# identifier", entry.Location));
                valid = false;
            }
            else if (IsReserved(entry.Name))
            {
                errors.Add(new ErrorInfo(ReservedName, "Sv schema", $"sv: name '{entry.Name}' collides with a generated member name", entry.Location));
                valid = false;
            }

            if (entry.Kind == IntrinsicKind)
            {
                if (!seenIntrinsics.Add(entry.Name))
                {
                    errors.Add(new ErrorInfo(DuplicateName, "Sv schema", $"sv: duplicate intrinsic '{entry.Name}'", entry.Location));
                    valid = false;
                }

                if (allStatNames.Contains(entry.Name))
                {
                    errors.Add(new ErrorInfo(DuplicateName, "Sv schema", $"sv: name '{entry.Name}' is declared as both stat and intrinsic", entry.Location));
                    valid = false;
                }

                if (valid)
                {
                    entries.Add(new StatEntry(IntrinsicKind, entry.Name, 0f, EmptySources));
                }

                continue;
            }

            if (!seenStats.Add(entry.Name))
            {
                errors.Add(new ErrorInfo(DuplicateName, "Sv schema", $"sv: duplicate stat '{entry.Name}'", entry.Location));
                valid = false;
            }

            if (allIntrinsicNames.Contains(entry.Name))
            {
                errors.Add(new ErrorInfo(DuplicateName, "Sv schema", $"sv: name '{entry.Name}' is declared as both stat and intrinsic", entry.Location));
                valid = false;
            }

            if (!IsFinite(entry.Base))
            {
                errors.Add(new ErrorInfo(NonFinite, "Sv schema", $"sv: stat '{entry.Name}' base must be finite", entry.Location));
                valid = false;
            }

            var sources = new List<(string Name, float Coefficient)>();
            if (entry.Kind == DerivedKind)
            {
                if (entry.LengthMismatch)
                {
                    errors.Add(new ErrorInfo(LengthMismatch, "Sv schema", $"sv: derived stat '{entry.Name}' needs equally many sources and coefficients", entry.Location));
                    valid = false;
                }

                if (entry.Sources.Length == 0)
                {
                    errors.Add(new ErrorInfo(LengthMismatch, "Sv schema", $"sv: derived stat '{entry.Name}' needs at least one source", entry.Location));
                    valid = false;
                }

                for (var i = 0; i < entry.Sources.Length; i++)
                {
                    var source = entry.Sources[i];
                    if (!allStatNames.Contains(source.Name))
                    {
                        errors.Add(new ErrorInfo(UnknownSource, "Sv schema", $"sv: derived stat '{entry.Name}' source '{source.Name}' is not a declared stat", entry.Location));
                        valid = false;
                    }
                        else if (!seenStats.Contains(source.Name) || source.Name == entry.Name)
                    {
                        errors.Add(new ErrorInfo(ForwardSource, "Sv schema", $"sv: derived stat '{entry.Name}' source '{source.Name}' must be declared before it", entry.Location));
                        valid = false;
                    }

                    if (!IsFinite(source.Coefficient))
                    {
                        errors.Add(new ErrorInfo(NonFinite, "Sv schema", $"sv: derived stat '{entry.Name}' coefficient for '{source.Name}' must be finite", entry.Location));
                        valid = false;
                    }

                    sources.Add((source.Name, source.Coefficient));
                }
            }

            if (valid)
            {
                entries.Add(new StatEntry(entry.Kind, entry.Name, entry.Base, new EquatableArray<(string, float)>(sources.ToImmutableArray())));
            }
        }

        if (entries.Count == 0 && errors.Count == 0)
        {
            errors.Add(new ErrorInfo(EmptySchema, "Sv schema", "sv: schema declares no stats and no intrinsics", LocationInfo.From(node.GetLocation())));
        }

        return new SchemaModel(NamespaceOf(symbol), symbol.Name, AccessibilityOf(symbol), new EquatableArray<StatEntry>(entries.ToImmutableArray()), ToErrors(errors), true);
    }

    static readonly EquatableArray<(string, float)> EmptySources = new(ImmutableArray<(string, float)>.Empty);

    static List<RawEntry> CollectRaw(INamedTypeSymbol symbol, CancellationToken ct)
    {
        var raw = new List<RawEntry>();
        foreach (var attribute in symbol.GetAttributes())
        {
            ct.ThrowIfCancellationRequested();
            var typeName = attribute.AttributeClass?.ToDisplayString();
            if (typeName == "Sv.SvStatAttribute")
            {
                raw.Add(new RawEntry(
                    StatKind,
                    ArgString(attribute, 0),
                    ArgFloat(attribute, 1),
                    Array.Empty<(string, float)>(),
                    false,
                    LocationInfo.From(AttributeLocation(attribute))));
            }
            else if (typeName == "Sv.SvDerivedAttribute")
            {
                var names = ArgStrings(attribute, 2);
                var coefficients = ArgFloats(attribute, 3);
                var mismatch = names.Length != coefficients.Length;
                var count = Math.Max(names.Length, coefficients.Length);
                var sources = new (string Name, float Coefficient)[count];
                for (var i = 0; i < count; i++)
                {
                    sources[i] = (
                        i < names.Length ? names[i] : string.Empty,
                        i < coefficients.Length ? coefficients[i] : float.NaN);
                }

                raw.Add(new RawEntry(DerivedKind, ArgString(attribute, 0), ArgFloat(attribute, 1), sources, mismatch, LocationInfo.From(AttributeLocation(attribute))));
            }
            else if (typeName == "Sv.SvIntrinsicAttribute")
            {
                raw.Add(new RawEntry(
                    IntrinsicKind,
                    ArgString(attribute, 0),
                    0f,
                    Array.Empty<(string, float)>(),
                    false,
                    LocationInfo.From(AttributeLocation(attribute))));
            }
        }

        return raw;
    }

    static Location? AttributeLocation(AttributeData attribute)
    {
        return attribute.ApplicationSyntaxReference?.GetSyntax().GetLocation();
    }

    static string ArgString(AttributeData attribute, int index)
    {
        var arguments = attribute.ConstructorArguments;
        return index < arguments.Length && arguments[index].Value is string value ? value : string.Empty;
    }

    static float ArgFloat(AttributeData attribute, int index)
    {
        var arguments = attribute.ConstructorArguments;
        return index < arguments.Length && arguments[index].Value is float value ? value : float.NaN;
    }

    static string[] ArgStrings(AttributeData attribute, int index)
    {
        var arguments = attribute.ConstructorArguments;
        if (index >= arguments.Length || arguments[index].Kind != TypedConstantKind.Array)
        {
            return Array.Empty<string>();
        }

        var values = arguments[index].Values;
        var result = new string[values.Length];
        for (var i = 0; i < values.Length; i++)
        {
            result[i] = values[i].Value as string ?? string.Empty;
        }

        return result;
    }

    static float[] ArgFloats(AttributeData attribute, int index)
    {
        var arguments = attribute.ConstructorArguments;
        if (index >= arguments.Length || arguments[index].Kind != TypedConstantKind.Array)
        {
            return Array.Empty<float>();
        }

        var values = arguments[index].Values;
        var result = new float[values.Length];
        for (var i = 0; i < values.Length; i++)
        {
            result[i] = values[i].Value is float value ? value : float.NaN;
        }

        return result;
    }

    static bool IsReserved(string name)
    {
        foreach (var reserved in Reserved)
        {
            if (reserved == name)
            {
                return true;
            }
        }

        return false;
    }

    static bool IsFinite(float value)
    {
        return !float.IsNaN(value) && !float.IsInfinity(value);
    }

    static bool IsValidIdentifier(string name)
    {
        if (name.Length == 0 || SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None)
        {
            return false;
        }

        if (!char.IsLetter(name[0]) && name[0] != '_')
        {
            return false;
        }

        for (var i = 1; i < name.Length; i++)
        {
            if (!char.IsLetterOrDigit(name[i]) && name[i] != '_')
            {
                return false;
            }
        }

        return true;
    }

    static string NamespaceOf(INamedTypeSymbol symbol)
    {
        return symbol.ContainingNamespace is { IsGlobalNamespace: false } space ? space.ToDisplayString() : string.Empty;
    }

    static string AccessibilityOf(INamedTypeSymbol symbol)
    {
        return symbol.DeclaredAccessibility switch
        {
            Accessibility.Public => "public",
            _ => "internal"
        };
    }

    static EquatableArray<ErrorInfo> ToErrors(List<ErrorInfo> errors)
    {
        errors.Sort(static (left, right) => string.CompareOrdinal(left.Id, right.Id));
        return new EquatableArray<ErrorInfo>(errors.ToImmutableArray());
    }
}
